/**
 * จำแนกมิติที่ 3 ของหนึ่งเสียง
 * 1) นับคำสำคัญในหัวข้อ + ข้อความ (หัวข้อมักสรุปประเด็นไว้แล้ว จึงรวมเข้าไปด้วย)
 * 2) ถ้าไม่เจอคำสำคัญเลย ใช้ cat_sales ช่วย
 * 3) ยังไม่ได้ → 'ด้านอื่น ๆ' (ไม่เดามั่ว — ตัวเลขที่เดาไว้จะทำให้ผู้บริหารตัดสินใจผิด)
 */
export function dim3Cat(r: Voc): string {
  const t = ((r.topic || '') + ' ' + (r.voice || '')).toLowerCase();
  let best = '', bs = 0;
  for (const [cat, kws] of DIM3_KW) {
    const sc = kws.reduce((a, [k, w]) => a + (t.includes(k) ? w : 0), 0);
    if (sc > bs) { bs = sc; best = cat; }
  }
  // ต้องได้อย่างน้อย 2 คะแนน — คำเดี่ยวน้ำหนัก 1 ไม่พอจะบอกว่าเสียงนี้พูดถึงด้านไหน
  // ถ้าปล่อยให้ผ่าน ตัวเลขจะดูสวยแต่ผิด ซึ่งอันตรายกว่าการบอกตรง ๆ ว่า "ยังจัดไม่ได้"
  if (bs >= 2) return best;
  const bySales = r.catSales ? SALES_TO_DIM3[r.catSales] : '';
  return bySales || DIM3_OTHER;
}

