// lib/pii.ts — ตรวจจับและกลบข้อมูลส่วนบุคคลในข้อความเสียงลูกค้า (PDPA)
//
// ทำไมต้องมี
//   เสียงลูกค้าที่รับมาจากช่องทางออนไลน์เป็นข้อความอิสระ ลูกค้ามักพิมพ์ข้อมูลตัวเองติดมาด้วย
//   เช่น "ผม นายสมชาย ใจดี บ้านเลขที่ 99/123 โทร 081-234-5678 เลขบัตร 1-1010-12345-67-8"
//   ถ้าเก็บดิบ ๆ ระบบ VOC จะกลายเป็นฐานข้อมูลส่วนบุคคลเต็มรูปแบบทันที
//   ถ้ากลบตั้งแต่ "ก่อนบันทึก" ข้อมูลที่เก็บจะระบุตัวบุคคลไม่ได้ ภาระตาม PDPA ลดลงมาก
//   และเนื้อหาที่เหลือยังใช้วิเคราะห์ความรู้สึก/ประเด็น/ฝ่ายผู้รับผิดชอบได้ครบเหมือนเดิม
//
// หลักการออกแบบ
//   1) **กลบ ไม่ใช่ลบ** — แทนที่ด้วยป้ายกำกับ เช่น [เบอร์โทร] เพื่อให้คนอ่านรู้ว่าตรงนี้เคยมีอะไร
//      ถ้าลบทิ้งเฉย ๆ ประโยคจะอ่านไม่รู้เรื่องและเจ้าหน้าที่จะไม่รู้ว่าข้อมูลหายไป
//   2) **ยอมพลาดฝั่งกลบเกิน ดีกว่าปล่อยหลุด** — แต่ต้องไม่กลบจนข้อความเสียความหมาย
//      จึงใช้ "คำบอกบริบท" ช่วยในกรณีที่ตัวเลขกำกวม (เลขที่สัญญา/เลขห้อง ไม่ใช่ข้อมูลระบุตัวตนเสมอไป)
//   3) **เลข 13 หลักต้องตรวจ checksum** ก่อนตัดสินว่าเป็นเลขบัตรประชาชน
//      ไม่งั้นเลขอื่น ๆ ที่ยาวพอกันจะถูกกลบมั่วไปหมด
//
// ⚠️ สิ่งที่เครื่องมือนี้ทำไม่ได้ และห้ามเข้าใจผิด
//   - จับชื่อคนที่ไม่มีคำนำหน้าไม่ได้ ("สมชายโทรมาแจ้ง" จะไม่ถูกกลบ)
//   - เป็นการ "ลดความเสี่ยง" ไม่ใช่การทำให้ข้อมูลไม่ใช่ข้อมูลส่วนบุคคลโดยสมบูรณ์
//     ยังต้องมีประกาศความเป็นส่วนตัว ฐานทางกฎหมาย และระยะเวลาเก็บรักษาเสมอ

export type PiiKind =
  | 'เลขบัตรประชาชน' | 'เบอร์โทร' | 'อีเมล' | 'ชื่อ-สกุล' | 'ที่อยู่'
  | 'เลขที่บัญชี' | 'ทะเบียนรถ' | 'ไอดีโซเชียล' | 'ลิงก์โปรไฟล์';

export interface PiiHit { kind: PiiKind; text: string; index: number }

/** ตรวจ checksum เลขประจำตัวประชาชนไทย 13 หลัก — หลักที่ 13 คือเลขตรวจสอบ */
export function isThaiId(digits: string): boolean {
  if (!/^\d{13}$/.test(digits)) return false;
  let sum = 0;
  for (let i = 0; i < 12; i++) sum += Number(digits[i]) * (13 - i);
  return (11 - (sum % 11)) % 10 === Number(digits[12]);
}

// ลำดับสำคัญ: กฎที่เจาะจงกว่าต้องมาก่อน ไม่งั้นกฎกว้างจะกินข้อความไปก่อน
// (เช่น อีเมลต้องมาก่อนไอดีไลน์ ไม่งั้น "a@b.com" โดนจับเป็นไอดี)
const RULES: { kind: PiiKind; re: RegExp; keep?: (m: string) => boolean }[] = [
  // อีเมล
  { kind: 'อีเมล', re: /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g },
  // ลิงก์โปรไฟล์โซเชียล
  { kind: 'ลิงก์โปรไฟล์', re: /https?:\/\/(?:www\.)?(?:facebook|fb|m\.facebook|line|instagram|x|twitter|tiktok)\.[^\s]+/gi },
  // เลขบัตรประชาชน — รับทั้งแบบมีขีด/เว้นวรรค แล้วค่อยตรวจ checksum
  // (?<![\d-]) / (?![\d-]) = ต้องไม่มีตัวเลขติดหัวท้าย กันจับครึ่ง ๆ กลาง ๆ ของเลขยาว
  { kind: 'เลขบัตรประชาชน', re: /(?<![\d-])\d[\s-]?\d{4}[\s-]?\d{5}[\s-]?\d{2}[\s-]?\d(?![\d-])/g,
    keep: m => isThaiId(m.replace(/[\s-]/g, '')) },
  // เลขที่บัญชีธนาคารไทยแบบมีขีด 3-1-5-1 (เช่น 123-4-56789-0)
  //   รูปแบบนี้เฉพาะเจาะจงพอ จึงกลบได้โดยไม่ต้องมีคำว่า "บัญชี" นำหน้า
  //   ต้องมาก่อนกฎเบอร์โทร และต้องมีขอบเขตหัวท้าย กันไปกินเลขยาวอื่นตรงกลาง
  { kind: 'เลขที่บัญชี', re: /(?<![\d-])\d{3}-\d-\d{5}-\d(?![\d-])/g },
  // เบอร์โทรไทย: 0X-XXX-XXXX / 0XXXXXXXXX / +66XXXXXXXXX (มือถือ 10 หลัก, บ้าน 9 หลัก)
  // 🚨 ขอบเขตหัวท้ายสำคัญมาก — ไม่มีแล้ว เลข 13 หลักที่ไม่ผ่าน checksum บัตรประชาชน
  //    จะถูกกฎนี้กินตรงกลางเป็น "11[เบอร์โทร]5" (เจอจริงตอนทดสอบ)
  { kind: 'เบอร์โทร', re: /(?<![\d-])(?:\+66[\s-]?|0)\d(?:[\s-]?\d){7,8}(?![\d-])/g },
  // ไอดีไลน์/โซเชียล ที่เขียนบอกไว้ชัด ๆ
  { kind: 'ไอดีโซเชียล', re: /(?:ไลน์\s*(?:ไอ?ดี)?|line\s*id|ไอดีไลน์|ig|อินสตาแกรม)\s*[:：]?\s*@?[A-Za-z0-9._-]{3,}/gi },
  // ชื่อ-สกุล ที่มีคำนำหน้า — จับได้เฉพาะกรณีมีคำนำหน้าเท่านั้น
  { kind: 'ชื่อ-สกุล', re: /(?:นาย|นางสาว|นาง|น\.ส\.|ด\.ช\.|ด\.ญ\.|คุณ)\s?[ก-๙]{2,}(?:\s+[ก-๙]{2,})?/g },
  // ที่อยู่ — บ้านเลขที่/เลขที่ห้อง ต้องมีคำบอกบริบทนำหน้าเสมอ
  { kind: 'ที่อยู่', re: /(?:บ้านเลขที่|เลขที่บ้าน|ที่อยู่|อาศัยอยู่ที่)\s*[:：]?\s*[\d/\-]+(?:\s*(?:หมู่|ม\.)\s*\d+)?/g },
  // เลขที่บัญชีธนาคาร — ต้องมีคำบอกบริบท ไม่งั้นเลขอะไรก็โดนกลบ
  //   คำบอกบริบท — ครอบคลุมสำนวนที่พบจริงในเสียงลูกค้า เช่น "โอนเข้าบัญชี 1234567890"
  { kind: 'เลขที่บัญชี', re: /(?:เลขที่บัญชี|บัญชีเลขที่|เลขบัญชี|บัญชีธนาคาร|เลขบช\.?|บช\.?|โอนเข้าบัญชี|เข้าบัญชี|บัญชี)\s*[:：]?\s*[\d-]{9,}/g },
  // ทะเบียนรถ เช่น 1กก 1234 / กท 1234
  { kind: 'ทะเบียนรถ', re: /(?:ทะเบียนรถ|ทะเบียน)\s*[:：]?\s*\d?[ก-ฮ]{1,2}\s?\d{1,4}/g },
];

/** หา PII ทั้งหมดในข้อความ (ไม่แก้ข้อความ) — ใช้แสดงผลตอนพรีวิวก่อนนำเข้า */
export function findPII(text: string): PiiHit[] {
  const s = text || '';
  const hits: PiiHit[] = [];
  const taken: [number, number][] = [];
  const overlaps = (a: number, b: number) => taken.some(([x, y]) => a < y && b > x);
  for (const r of RULES) {
    r.re.lastIndex = 0;
    let m: RegExpExecArray | null;
    while ((m = r.re.exec(s)) !== null) {
      const a = m.index, b = a + m[0].length;
      if (overlaps(a, b)) continue;             // กฎก่อนหน้าจับไปแล้ว อย่าจับซ้อน
      if (r.keep && !r.keep(m[0])) continue;    // ไม่ผ่านการตรวจสอบ (เช่น checksum บัตรประชาชน)
      taken.push([a, b]);
      hits.push({ kind: r.kind, text: m[0], index: a });
    }
  }
  return hits.sort((x, y) => x.index - y.index);
}

/** กลบ PII ด้วยป้ายกำกับ — ผลลัพธ์นี้คือสิ่งที่ควรบันทึกลงฐานข้อมูล ไม่ใช่ข้อความดิบ */
export function maskPII(text: string): { masked: string; hits: PiiHit[] } {
  const hits = findPII(text || '');
  let out = text || '';
  // แทนที่จากท้ายมาหน้า ตำแหน่ง index ของตัวที่ยังไม่ถูกแทนจะได้ไม่เลื่อน
  for (let i = hits.length - 1; i >= 0; i--) {
    const h = hits[i];
    out = out.slice(0, h.index) + '[' + h.kind + ']' + out.slice(h.index + h.text.length);
  }
  return { masked: out, hits };
}

/** สรุปจำนวนที่พบแยกตามประเภท — ใช้รายงานให้ผู้ดูแลเห็นว่ากลบอะไรไปบ้าง */
export function summarizePII(hits: PiiHit[]): Record<string, number> {
  const m: Record<string, number> = {};
  for (const h of hits) m[h.kind] = (m[h.kind] ?? 0) + 1;
  return m;
}
