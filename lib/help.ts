// หลักการเขียนคู่มือนี้ (อย่าเขียนเป็นคู่มือ "อธิบายปุ่ม")
//   คนเปิดคู่มือเพราะ "อยากทำอะไรสักอย่างให้สำเร็จ" ไม่ใช่อยากรู้ว่าปุ่มนี้ชื่ออะไร
//   เนื้อหาจึงเรียงตาม **งานที่ต้องทำ** (task) ไม่ใช่ตามเมนู แล้วบอกเป็นขั้นตอนนับ 1-2-3
//   ทุกงานมีลิงก์ไปหน้าจริง เพื่อให้อ่านแล้วลงมือได้ทันทีโดยไม่ต้องหาเมนูเอง
//
// ⚠️ กติกาสำคัญ: เนื้อหาต้องตรงกับระบบจริงเสมอ
//   ชื่อเมนู ชื่อปุ่ม และจำนวนขั้นตอน ต้องตรงกับที่เห็นบนหน้าจอเป๊ะ ๆ
//   ถ้าเปลี่ยนชื่อเมนูหรือขั้นตอนในระบบเมื่อไร ต้องมาแก้ไฟล์นี้ด้วย ไม่งั้นคู่มือจะสอนผิด

export type RoleKey = 'executive' | 'operator' | 'admin';

export interface Step { text: string; tip?: string }
export interface Task {
  id: string;
  title: string;             // ตั้งชื่อเป็น "สิ่งที่ผู้ใช้อยากทำ" ไม่ใช่ชื่อฟีเจอร์
  why: string;               // ทำไปทำไม — คนอ่านจะได้รู้ว่าควรอ่านต่อไหม
  menu?: string;             // เมนูที่ใช้ (ชื่อตรงกับแถบซ้าย)
  href?: string;             // ลิงก์ไปหน้าจริง
  minutes?: number;          // ใช้เวลาประมาณกี่นาที
  steps: Step[];
  notes?: string[];          // ข้อควรรู้/กับดักที่คนมักพลาด
}
export interface TaskGroup { group: string; icon: string; tasks: Task[] }

export interface RoleInfo {
  key: RoleKey; icon: string; name: string; short: string;
  can: string[];             // ทำอะไรได้บ้าง
  cannot: string[];          // ทำอะไรไม่ได้ (บอกให้ชัด จะได้ไม่ไปตามหาเมนูที่ไม่มี)
  color: string;
}

