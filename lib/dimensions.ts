export interface Bucket { key: string; n: number; pos: number; neu: number; neg: number; high: number }

/** นับเสียงตามคีย์ที่กำหนด พร้อมแยกอารมณ์ในคราวเดียว (วนข้อมูลรอบเดียว — 10,000 แถวจึงไม่หน่วง) */
export function bucketBy(rows: Voc[], keyOf: (r: Voc) => string, order?: readonly string[]): Bucket[] {
  const m = new Map<string, Bucket>();
  const touch = (k: string) => {
    let b = m.get(k);
    if (!b) { b = { key: k, n: 0, pos: 0, neu: 0, neg: 0, high: 0 }; m.set(k, b); }
    return b;
  };
  if (order) order.forEach(k => touch(k));   // คงลำดับที่กำหนดไว้ แม้หมวดนั้นจะยังไม่มีข้อมูล
  rows.forEach(r => {
    const b = touch(keyOf(r));
    b.n++;
    if (r.sentiment === 'Positive') b.pos++;
    else if (r.sentiment === 'Negative') b.neg++;
    else b.neu++;
    if (r.priority === 'High') b.high++;
  });
  const out = Array.from(m.values());
  return order ? out : out.sort((a, b) => b.n - a.n);
}

/** ประเด็นที่พบบ่อยที่สุดในชุดข้อมูลย่อย */
export function topTopics(rows: Voc[], n = 5): [string, number][] {
  const m: Record<string, number> = {};
  rows.forEach(r => { if (r.topic) m[r.topic] = (m[r.topic] || 0) + 1; });
  return Object.entries(m).sort((a, b) => b[1] - a[1]).slice(0, n);
}

