//   ระบบจริง (production)      ไม่ตั้ง NEXT_PUBLIC_DEMO_MODE → ต้องล็อกอิน · ข้อมูลประชาชนจริง
//   เว็บสาธิต (demo)           NEXT_PUBLIC_DEMO_MODE=1        → เข้าดูได้เลย · ข้อมูลจำลอง 10,012 รายการ
//
// ====== กุญแจสองดอก (ห้ามลดเหลือดอกเดียว) ======
// การ "เข้าดูได้โดยไม่ต้องล็อกอิน" เกิดขึ้นได้ต้องครบ 2 เงื่อนไขพร้อมกัน
//   ดอกที่ 1 (โค้ด)       IS_DEMO === true  คือตั้ง NEXT_PUBLIC_DEMO_MODE=1 ที่ Vercel โปรเจกต์นั้น
//   ดอกที่ 2 (ฐานข้อมูล) Postgres เปิดสิทธิ์ SELECT ให้ role `anon` (ทำเฉพาะฐานสาธิต)
//
// ผลคือ **ถ้าเผลอตั้ง NEXT_PUBLIC_DEMO_MODE=1 บนระบบจริง จะไม่เกิดการรั่วของข้อมูล**
// เพราะฐานข้อมูลจริงไม่ได้เปิดสิทธิ์ให้ anon — หน้าเว็บจะขึ้น 0 รายการ (หรือถอยไปใช้ข้อมูลตัวอย่างในโค้ด)
// ไม่ใช่เปิดเผยเสียงลูกค้าจริงต่อคนที่ไม่ได้ล็อกอิน
//
// ⚠️ ห้ามทำสองอย่างนี้เด็ดขาด
//   1) ห้ามเปิดสิทธิ์ SELECT ให้ anon บนฐานข้อมูล "จริง" ไม่ว่าด้วยเหตุผลใด
//   2) ห้ามทำปุ่มสาธารณะที่ชี้ไปอ่านฐานข้อมูล "จริง" ชุดเดียวกับระบบจริง
//      (ลืมกรองจุดเดียว = ข้อมูลประชาชนหลุดถึงคนที่ไม่ได้ล็อกอินทันที)

/** true = เว็บนี้คือ "เว็บสาธิต" (เข้าดูได้โดยไม่ต้องล็อกอิน แสดงข้อมูลจำลอง) */
export const IS_DEMO = process.env.NEXT_PUBLIC_DEMO_MODE === '1';

/** ลิงก์เว็บสาธิต — ตั้งค่าบน **ระบบจริง** เพื่อให้ปุ่ม "ดูระบบตัวอย่าง" โผล่ที่หน้าล็อกอิน
 *  ไม่ตั้งค่า = ไม่มีปุ่ม (หน้าล็อกอินของระบบจริงเหมือนเดิมทุกอย่าง) */
export const DEMO_URL = process.env.NEXT_PUBLIC_DEMO_URL || '';

/** ลิงก์ระบบจริง — ตั้งค่าบน **เว็บสาธิต** เพื่อให้มีทางกลับไปหน้าล็อกอินของระบบจริง */
export const PROD_URL = process.env.NEXT_PUBLIC_PROD_URL || '';

/** ข้อความกำกับบนทุกหน้าของเว็บสาธิต */
export const DEMO_NOTE = 'ข้อมูลจำลองเพื่อการสาธิต';

/** ====== เว็บสาธิตมีเมนูครบเหมือนระบบจริง ======
 *
 *  เดิมเว็บสาธิตซ่อน 3 เมนู (นำเข้าข้อมูล · คิวรอยืนยัน · จัดการระบบ) แล้วเด้งออกที่ middleware
 *  ผลคือผู้ประเมินเห็นระบบไม่ครบ และตัดสินความสามารถของระบบจากเมนูที่เหลือเท่านั้น
 *
 *  ตอนนี้เปลี่ยนเป็น **แสดงทุกเมนู เปิดดูหน้าจอจริงได้ แต่แก้ไขอะไรไม่ได้**
 *  แต่ละหน้าปิดปุ่มที่เขียนข้อมูลเอง (ดู role === 'demo' ในหน้านั้น ๆ)
 *
 *  ⚠️ ชั้นที่กันข้อมูลเปลี่ยนจริง ๆ ไม่ใช่โค้ดหน้าเว็บ แต่คือ **ฐานสาธิตถูกถอนสิทธิ์เขียนทั้งฐาน**
 *     (แยกข้อมูลสาธิต/4_ล็อกฐานสาธิตให้อ่านอย่างเดียว.sql — ถอน insert/update/delete ทุกตารางจาก anon)
 *     ปุ่มที่ปิดในหน้าเว็บเป็นเรื่องของประสบการณ์ผู้ใช้ ไม่ใช่ด่านความปลอดภัย
 *
 *  ข้อยกเว้นเดียวที่ยัง "ไม่แสดง" คือ ตารางรายชื่อผู้ใช้/อีเมลเจ้าหน้าที่ ในหน้าจัดการระบบ
 *  เพราะเว็บสาธิตใครเปิดก็ได้ จึงไม่ควรมีชื่อและอีเมลคนจริงอยู่บนนั้น (ดู app/admin/page.tsx)
 */
export const DEMO_ROLE = 'demo';

