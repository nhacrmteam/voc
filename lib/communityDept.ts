export const COMMUNITY_GENERIC = 'ฝ่ายบริหารงานชุมชน';

const CM_NORTH = 'ฝ่ายบริหารงานชุมชนภาคเหนือ';
const CM_NE    = 'ฝ่ายบริหารงานชุมชนภาคตะวันออกเฉียงเหนือ';
const CM_SOUTH = 'ฝ่ายบริหารงานชุมชนภาคใต้';
const CM_CE    = 'ฝ่ายบริหารงานชุมชนภาคกลางและภาคตะวันออก';

const mapProv = (dept: string, provs: string[]) => provs.map(p => [p, dept] as const);

export const COMMUNITY_DEPT_BY_PROVINCE: Record<string, string> = Object.fromEntries([
  ...mapProv(CM_NORTH, ['เชียงใหม่', 'เชียงราย', 'ลำปาง', 'ลำพูน', 'แม่ฮ่องสอน', 'น่าน', 'พะเยา', 'แพร่', 'อุตรดิตถ์',
    'ตาก', 'สุโขทัย', 'พิษณุโลก', 'พิจิตร', 'เพชรบูรณ์', 'กำแพงเพชร', 'นครสวรรค์', 'อุทัยธานี']),
  ...mapProv(CM_NE, ['นครราชสีมา', 'ขอนแก่น', 'อุดรธานี', 'อุบลราชธานี', 'ชัยภูมิ', 'บุรีรัมย์', 'สุรินทร์', 'ศรีสะเกษ',
    'ยโสธร', 'อำนาจเจริญ', 'มุกดาหาร', 'นครพนม', 'สกลนคร', 'กาฬสินธุ์', 'มหาสารคาม', 'ร้อยเอ็ด',
    'หนองคาย', 'บึงกาฬ', 'หนองบัวลำภู', 'เลย']),
  ...mapProv(CM_SOUTH, ['สงขลา', 'ภูเก็ต', 'สุราษฎร์ธานี', 'นครศรีธรรมราช', 'กระบี่', 'พังงา', 'ระนอง', 'ชุมพร',
    'ตรัง', 'พัทลุง', 'สตูล', 'ปัตตานี', 'ยะลา', 'นราธิวาส']),
  ...mapProv(CM_CE, ['ชลบุรี', 'ระยอง', 'จันทบุรี', 'ตราด', 'ฉะเชิงเทรา', 'ปราจีนบุรี', 'สระแก้ว', 'นครนายก',
    'พระนครศรีอยุธยา', 'อ่างทอง', 'ลพบุรี', 'สิงห์บุรี', 'ชัยนาท', 'สระบุรี', 'สุพรรณบุรี',
    'ราชบุรี', 'กาญจนบุรี', 'เพชรบุรี', 'ประจวบคีรีขันธ์', 'สมุทรสงคราม']),
  // กรุงเทพมหานคร · นนทบุรี · ปทุมธานี · สมุทรปราการ · สมุทรสาคร · นครปฐม → รอรายชื่อจาก ฝ่ายการตลาด
]);

/** เลือกฝ่ายบริหารงานชุมชนจากจังหวัดของโครงการ — ไม่รู้จังหวัด/ยังไม่ได้แมป = ไม่เดา */
export function communityDeptFor(province?: string | null): string {
  const p = (province ?? '').trim();
  return COMMUNITY_DEPT_BY_PROVINCE[p] ?? COMMUNITY_GENERIC;
}
